  get(key, fallback = null) {
    try { return localStorage.getItem(key) ?? fallback; }
    catch (error) { console.warn(`Unable to read local setting: ${key}`, error); return fallback; }
  },
  set(key, value) {
    try { localStorage.setItem(key, String(value)); return true; }
    catch (error) { console.warn(`Unable to save local setting: ${key}`, error); return false; }
  },
  remove(key) {
    try { localStorage.removeItem(key); return true; }
    catch (error) { console.warn(`Unable to remove local setting: ${key}`, error); return false; }
  },
  getJSON(key, fallback) {
    const raw = this.get(key);
    if (raw == null) return fallback;
    try { return JSON.parse(raw); }
    catch (error) { console.warn(`Invalid local data was cleared: ${key}`, error); this.remove(key); return fallback; }
  },
  setJSON(key, value) {
    try { return this.set(key, JSON.stringify(value)); }
    catch (error) { console.warn(`Unable to serialize local setting: ${key}`, error); return false; }
  }
