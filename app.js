const onboardingState = { screen: 1, timers: [], mode: 'mobile' };

function clearOnboardingTimers() {
  onboardingState.timers.forEach(clearTimeout);
  onboardingState.timers = [];
}

function showOnboardingScreen(screen, immediate = false) {
  const next = $(`[data-onboarding-screen="${screen}"]`);
  const current = $('.onboarding-screen.is-active');
  if (!next || next === current) return;
  onboardingState.screen = screen;
  if (current) current.classList.remove('is-active');
  const reveal = () => {
    $$('.onboarding-screen').forEach(item => { item.hidden = item !== next; });
    requestAnimationFrame(() => next.classList.add('is-active'));
    if (screen === 3) startProfileBuild();
    if (screen === 4) $('#onboardingProfileMode').textContent = onboardingState.mode === 'guest' ? 'Guest profile · Demo data' : 'Mobile profile · Demo data';
  };
  if (immediate) reveal(); else setTimeout(reveal, 200);
}

function startProfileBuild() {
  clearOnboardingTimers();
  $$('.profile-sequence [data-profile-line]').forEach(line => line.classList.remove('visible'));
  const schedule = (delay, action) => onboardingState.timers.push(setTimeout(action, delay));
  schedule(500, () => $('[data-profile-line="1"]').classList.add('visible'));
  schedule(1500, () => $('[data-profile-line="2"]').classList.add('visible'));
  schedule(2500, () => $('[data-profile-line="3"]').classList.add('visible'));
  schedule(3500, () => { onboardingState.timers = []; showOnboardingScreen(4); });
}

function finishOnboarding(remind = false) {
  clearOnboardingTimers();
  storage.set('ps_onboarded', 'true');
  storage.set('ps-access-mode', onboardingState.mode === 'guest' ? 'guest' : 'mobile');
  const overlay = $('#onboardingOverlay');
  overlay.hidden = true;
  overlay.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
  syncAccessExperience();
  navigate('home');
  if (remind) toast('DL reminder set for one week from today');
}

function initializeOnboarding() {
  const overlay = $('#onboardingOverlay');
  const resetButton = $('#resetOnboarding');
  try {
    const demoMode = pageParams.get('demo') === 'onboarding';
    const showOnboarding = !judgeMode && (demoMode || !storage.get('ps_onboarded'));
    resetButton.hidden = !demoMode;
    if (!showOnboarding) return;

    onboardingState.screen = 1;
    $$('.onboarding-screen').forEach(screen => {
      const first = screen.dataset.onboardingScreen === '1';
      screen.hidden = !first;
      screen.classList.toggle('is-active', first);
    });
    overlay.hidden = false;
    overlay.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';

    $('#onboardingStart').addEventListener('click', () => showOnboardingScreen(2));
    $('#onboardingBack').addEventListener('click', () => showOnboardingScreen(1));
    const mobileInput = $('#onboardingMobile');
    const continueButton = $('#onboardingContinue');
    mobileInput.value = storage.get('ps-demo-mobile', '');
    continueButton.disabled = !/^\d{10}$/.test(mobileInput.value);
    mobileInput.addEventListener('input', () => {
      mobileInput.value = mobileInput.value.replace(/\D/g, '').slice(0, 10);
      continueButton.disabled = !/^\d{10}$/.test(mobileInput.value);
    });
    continueButton.addEventListener('click', () => {
      if (continueButton.disabled) return;
      onboardingState.mode = 'mobile'; storage.set('ps-demo-mobile', mobileInput.value); storage.set('ps-access-mode', 'mobile'); showOnboardingScreen(3);
    });
    $('#onboardingGuest').addEventListener('click', () => {
      onboardingState.mode = 'guest';
      storage.remove('ps-demo-mobile');
      storage.set('ps-access-mode', 'guest');
      finishOnboarding(false);
      toast('Guest mode · Sign in only when you want to save');
    });
    $('#onboardingFinish').addEventListener('click', () => finishOnboarding(false));
    $('#onboardingRemind').addEventListener('click', () => finishOnboarding(true));
    resetButton.addEventListener('click', () => { storage.remove('ps_onboarded'); storage.remove('ps-demo-mobile'); storage.remove('ps-access-mode'); location.reload(); });
  } catch (error) {
    console.warn('Onboarding unavailable; continuing to dashboard.', error);
    clearOnboardingTimers();
    overlay.hidden = true;
    overlay.setAttribute('aria-hidden', 'true');
    resetButton.hidden = true;
    document.body.style.overflow = '';
  }
}

