function isValidVehicleNumber(value = '') {
  return /^[A-Z]{2}\d{1,2}[A-Z]{1,3}\d{4}$/.test(String(value).replace(/\s/g, '').toUpperCase());
}

function isValidTenDigitPhone(value = '') {
  return /^\d{10}$/.test(String(value));
}

function isValidPin(value = '') {
  return /^\d{6}$/.test(String(value));
}

function isValidTravelWindow(departure, returnDate) {
  return Boolean(departure && returnDate && returnDate >= departure);
}

