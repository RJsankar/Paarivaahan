function escapeFlowValue(value = '') {
  return String(value).replace(/[&<>"]/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[character]));
}

function flowActions(primaryLabel, { disabled = false, back = true, next = true } = {}) {
  return `<div class="flow-actions${back ? '' : ' single'}">${back ? '<button class="flow-secondary" data-flow-action="back">← Back</button>' : ''}${next ? `<button class="flow-primary" data-flow-action="next" ${disabled ? 'disabled' : ''}>${primaryLabel}</button>` : ''}</div>`;
}

