function handleDocument(file) {
  if (!file) { toast('Choose a JPG, PNG or PDF document to continue.'); return false; }
  const extension = file.name?.split('.').pop()?.toLowerCase();
  const allowedType = ['image/jpeg','image/png','application/pdf'].includes(file.type) || ['jpg','jpeg','png','pdf'].includes(extension);
  if (!allowedType) { toast('Unsupported file. Choose a JPG, PNG or PDF document.'); return false; }
  if (!file.size) { toast('This file is empty. Choose another document.'); return false; }
  if (file.size > 10 * 1024 * 1024) { toast('This file is larger than 10 MB. Choose a smaller document.'); return false; }
  navigate('documents');
  resetAnalysis();
  $('#fileName').textContent = file?.name || 'Sample challan · checking details and confidence';
  $('#analysisLoading').hidden = false; $('#analysisResult').hidden = true;
  $$('.analysis-steps span').forEach((step, i) => step.classList.toggle('done', i === 0));
  openModal('analysisModal');
  state.analysisTimers.push(setTimeout(() => $$('.analysis-steps span')[1].classList.add('done'), 650));
  state.analysisTimers.push(setTimeout(() => $$('.analysis-steps span')[2].classList.add('done'), 1250));
  state.analysisTimers.push(setTimeout(() => { $('#analysisLoading').hidden = true; $('#analysisResult').hidden = false; state.analysisTimers = []; }, 1850));
  return true;
}

